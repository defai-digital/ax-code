import fs from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import z from "zod"
import collection from "../src/provider/ax-engine/collection.json"
import { readBoundedBody } from "../src/util/http-body"
import { parseJsonStrict } from "../src/util/json-value"

const root = fileURLToPath(new URL("../../../", import.meta.url))
const repo = z.string().regex(/^AutomatosX\/[A-Za-z0-9][A-Za-z0-9._-]{0,199}$/)
const revision = z.string().regex(/^[a-f0-9]{40}$/)
const digest = z.string().regex(/^[a-f0-9]{64}$/)
const publicUrl = z.url().refine((value) => {
  const url = new URL(value)
  return (
    url.protocol === "https:" &&
    !url.username &&
    !url.password &&
    !url.port &&
    !url.search &&
    !url.hash &&
    !/[()<>\s]/.test(value) &&
    ["download.ax-code.com", "download.automatosx.com"].includes(url.hostname)
  )
})
export const ModelDownloadSnapshot = z.object({
  version: z.literal(1),
  checkedAt: z.iso.datetime(),
  models: z
    .array(
      z.object({
        repo,
        revision,
        private: z.boolean(),
        gated: z.union([z.boolean(), z.enum(["auto", "manual"])]),
        license: z.string().max(256),
      }),
    )
    .max(200),
})
export const ModelMirrorInventory = z.object({
  version: z.literal(1),
  mirrors: z
    .array(
      z.object({
        repo,
        revision,
        manifestUrl: publicUrl,
        signatureUrl: publicUrl,
        manifestSha256: digest,
        verificationReceipt: publicUrl,
        verifiedAt: z.iso.datetime(),
      }),
    )
    .max(200),
})
export type ModelDownloadSnapshot = z.infer<typeof ModelDownloadSnapshot>
export type ModelMirrorInventory = z.infer<typeof ModelMirrorInventory>

const cell = (value: string) => value.replace(/[<>&|\r\n]/g, " ").replace(/[[\]`]/g, "")

export function renderModelDownloads(snapshot: ModelDownloadSnapshot, inventory: ModelMirrorInventory): string {
  snapshot = ModelDownloadSnapshot.parse(snapshot)
  inventory = ModelMirrorInventory.parse(inventory)
  if (new Set(snapshot.models.map((model) => model.repo.toLowerCase())).size !== snapshot.models.length)
    throw new Error("Duplicate collection model")
  const mirrorIDs = inventory.mirrors.map((mirror) => `${mirror.repo}@${mirror.revision}`)
  if (new Set(mirrorIDs).size !== mirrorIDs.length) throw new Error("Duplicate mirror artifact")
  const selected = new Set<string>(collection.models)
  const rows = snapshot.models.map((model) => {
    const artifact = inventory.mirrors.find(
      (mirror) => mirror.repo === model.repo && mirror.revision === model.revision,
    )
    if (artifact && (model.private || model.gated))
      throw new Error("A private or gated collection model cannot be advertised as a public mirror")
    const mirror = artifact
      ? `[Manifest](${artifact.manifestUrl}) / [signature](${artifact.signatureUrl}) / [verification](${artifact.verificationReceipt})`
      : inventory.mirrors.some((mirror) => mirror.repo === model.repo)
        ? "No verified mirror for this revision"
        : "Not published"
    return `| ${cell(model.repo.replace("AutomatosX/", ""))} | [${model.revision.slice(0, 12)}](https://huggingface.co/${model.repo}/tree/${model.revision}) | ${selected.has(model.repo) ? "Selected" : "Pending review"} | ${cell(model.license)} | ${mirror} |`
  })
  return `# AX Code model downloads\n\nStatus: Active\nScope: current-state\nLast reviewed: ${snapshot.checkedAt.slice(0, 10)}\nOwner: ax-code runtime\n\n<!-- Generated by packages/ax-code/script/model-download-docs.ts. -->\n\nLast checked: ${snapshot.checkedAt}.\n\nThis page records the [AutomatosX/ax-code collection](${collection.url}) and exact download revisions. Selected models are in AX Code's reviewed collection; native readiness and tool support are still checked before use. These are observed publisher revisions, not a compatibility guarantee or a change to the revision pinned by an installed runtime. New collection entries remain pending review until explicitly admitted by the runtime.\n\nPublic, ungated Hugging Face models can be downloaded without an account. A personal HF login is optional for higher request limits; gated or private repositories require authorization.\n\n<!-- prettier-ignore -->\n| Model | Hugging Face revision | AX Code selection | Declared license | R2 mirror |\n| --- | --- | --- | --- | --- |\n${rows.join("\n")}\n\nR2 availability applies only to the exact revision above. A missing or stale mirror is not a download source. The mirror inventory records reviewed publication receipts; this page does not activate a mirror in the runtime. No R2 model mirrors are currently configured when every row says Not published.\n\nHF remains the active download source. R2 is not assumed faster: multi-GB model shards may exceed Cloudflare CDN cacheable-object limits. Mirror publication requires review of redistribution terms, signed manifests, file sizes and SHA-256 digests, and a verified download receipt. Preserve the selected HF cache location; existing local model directories can also be imported with AX Engine.\n\nIf Hugging Face is unavailable and the R2 mirror column links a manifest, download that manifest and every file it lists from https://download.ax-code.com/ax-code-models/. The copy for a revision lives under that prefix and is not mixed with release archives. Check each SHA-256, keep the files in one directory, and register them with \`ax-code providers ax-engine prepare --model-path <dir>\`. AX Code does not switch its own downloader to R2.\n\nSee the [publication workflow](model-download-publication.md) for updates. A publisher notification triggers a reviewable documentation proposal through the model-downloads workflow. Scheduled refreshes catch missed notifications. Runtime admission, R2 publication, and merging the proposal remain separate reviewed actions.\n`
}

async function getJson(url: string): Promise<unknown> {
  const response = await fetch(url, {
    signal: AbortSignal.timeout(15_000),
    redirect: "error",
    headers: { accept: "application/json" },
  })
  if (!response.ok) {
    await response.body?.cancel()
    throw new Error(`Model inventory request failed with HTTP ${response.status}`)
  }
  if (/\brel\s*=\s*["']?next\b/i.test(response.headers.get("link") ?? "")) {
    await response.body?.cancel()
    throw new Error("Paginated model inventory cannot be recorded as complete")
  }
  const value = parseJsonStrict(Buffer.from(await readBoundedBody(response, 2 * 1024 ** 2)).toString("utf8"))
  if (value && typeof value === "object" && !Array.isArray(value)) {
    const record = value as Record<string, unknown>
    if (["next", "next_page", "nextCursor"].some((key) => record[key]))
      throw new Error("Incomplete model inventory response")
  }
  return value
}

export async function refreshModelDownloads(previous: ModelDownloadSnapshot): Promise<ModelDownloadSnapshot> {
  const remote = z
    .object({ items: z.array(z.object({ type: z.string(), id: z.string().max(256) })).max(200) })
    .parse(await getJson("https://huggingface.co/api/collections/AutomatosX/ax-code"))
  const repositories = remote.items.filter((item) => item.type === "model").map((item) => repo.parse(item.id))
  if (!repositories.length || new Set(repositories.map((id) => id.toLowerCase())).size !== repositories.length)
    throw new Error("Empty or duplicate collection inventory")
  const models: ModelDownloadSnapshot["models"] = []
  for (let offset = 0; offset < repositories.length; offset += 4) {
    models.push(
      ...(await Promise.all(
        repositories.slice(offset, offset + 4).map(async (id) => {
          const model = z
            .object({
              id: repo,
              sha: revision,
              private: z.boolean(),
              gated: z.union([z.boolean(), z.enum(["auto", "manual"])]),
              cardData: z.object({ license: z.string().max(256).optional() }).nullish(),
            })
            .parse(await getJson(`https://huggingface.co/api/models/${id}`))
          if (model.id !== id) throw new Error("Hub model identity mismatch")
          return {
            repo: id,
            revision: model.sha,
            private: model.private,
            gated: model.gated,
            license: model.cardData?.license ?? "unspecified",
          }
        }),
      )),
    )
  }
  // Retain the last observation time when no metadata changed, avoiding daily PR churn.
  return {
    version: 1,
    checkedAt:
      JSON.stringify(models) === JSON.stringify(previous.models) ? previous.checkedAt : new Date().toISOString(),
    models,
  }
}

export async function syncModelDownloadDocs(options: { refresh?: boolean; check?: boolean } = {}) {
  const snapshotPath = path.join(root, "docs/data/ax-code-model-downloads.json")
  const mirrorPath = path.join(root, "docs/data/ax-code-model-mirrors.json")
  const pagePath = path.join(root, "docs/providers/ax-code-model-downloads.md")
  let snapshot = ModelDownloadSnapshot.parse(parseJsonStrict(await fs.readFile(snapshotPath, "utf8")))
  if (options.refresh) snapshot = await refreshModelDownloads(snapshot)
  const inventory = ModelMirrorInventory.parse(parseJsonStrict(await fs.readFile(mirrorPath, "utf8")))
  const page = renderModelDownloads(snapshot, inventory)
  if (options.check) {
    if ((await fs.readFile(pagePath, "utf8")) !== page) throw new Error("Model download documentation is out of date")
    return
  }
  // Prepare the complete candidate before replacing either checked-in file.
  await fs.writeFile(snapshotPath + ".tmp", JSON.stringify(snapshot, null, 2) + "\n")
  await fs.writeFile(pagePath + ".tmp", page)
  await fs.rename(snapshotPath + ".tmp", snapshotPath)
  await fs.rename(pagePath + ".tmp", pagePath)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await syncModelDownloadDocs({ refresh: process.argv.includes("--refresh"), check: process.argv.includes("--check") })
}
