import { fileURLToPath } from "node:url"
import { build } from "esbuild"
import { readFile, writeFile } from "node:fs/promises"
const result = await build({
  entryPoints: [fileURLToPath(new URL("../src/browser.ts", import.meta.url))],
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  write: false,
})
if (/<!--|<script|<\/script/i.test(result.outputFiles[0].text)) throw new Error("Unsafe inline browser bundle")
const source = `// Generated by script/bundle.mjs; do not edit.\n// prettier-ignore\nexport const browserBundle = ${JSON.stringify(result.outputFiles[0].text)}\n`
const target = new URL("../src/browser-bundle.ts", import.meta.url)
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")).replace(/\r\n/g, "\n") !== source)
    throw new Error("Viewer bundle is stale; run pnpm build")
} else await writeFile(target, source)
